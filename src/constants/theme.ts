/**
 * Slow, graceful, fluid — everything moves as if suspended in honey. The
 * previous system was near-instant and binary; this one is the opposite, so
 * every duration here is a deliberate reversal rather than a tweak.
 *
 * `easeOut` is the curve the brief names. React Native has no shared cubic
 * easing token, so screens pass `Easing.out(Easing.cubic)` to Reanimated and the
 * numbers below to `Animated`/`LayoutAnimation`.
 */
