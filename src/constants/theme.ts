/**
 * Botanical / Organic Serif design tokens.
 *
 * The system is a digital ode to nature: a warm alabaster ground, ink drawn from
 * a forest floor, and geometry that flows rather than cuts. Emphasis is carried
 * by *tone* (a deep-forest plate, a pale sage wash) instead of the previous
 * system's hard inversion, and by *soft elevation* instead of rules.
 *
 * Three commitments survive the change, because they are product truth rather
 * than styling:
 *
 *  1. Money direction never depends on hue alone. Sign, arrow and weight still
 *     carry it; `positive`/`negative` now reinforce that reading in colour, so a
 *     grayscale print or a colour-blind reader loses nothing.
 *  2. Every colour is read through `useTheme()`, never hard-coded, so light and
 *     dark resolve in exactly one place.
 *  3. Dark mode is a designed appearance, not an inversion: a forest-at-night
 *     ground with paper-toned ink, keeping the same rounded geometry.
 *
 * The paper grain the brief calls for lives in `assets/images/grain.png`, is
 * generated by `tools/generate-grain.mjs`, and is painted once by `<Grain />`.
 */

